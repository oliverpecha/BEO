#!/bin/bash
# ~/beo/scripts/util_litellm_rebuild.sh
# Reads GEMINI_KEY_N from .env (any indices, non-sequential), generates litellm_config.yaml
# Run: bash ~/beo/scripts/util_litellm_rebuild.sh

set -euo pipefail

ENV_FILE=~/openclaw/.env
CONFIG_OUT=/root/openclaw/litellm_config.yaml
SUMMARY_OUTPUT=""

# ── Collect all GEMINI_KEY_N indices present, sorted numerically ──────────────
INDICES=()
while IFS= read -r line; do
  varname=$(echo "$line" | cut -d= -f1)
  idx=${varname#GEMINI_KEY_}
  INDICES+=("$idx")
done < <(grep -E "^GEMINI_KEY_[0-9]+=" "$ENV_FILE" | sort -t_ -k3 -n)

if [[ ${#INDICES[@]} -eq 0 ]]; then
  echo "❌ [ERROR] No valid GEMINI_KEY_N entries found in $ENV_FILE"
  exit 1
fi

# ── Dynamic Model Emitters ────────────────────────────────────────────────────

emit_entries() {
  local model_name=$1
  local model=$2
  local extra_yaml=$3
  local label=${4:-$model_name}
  local url=${5:-""}
  local think_tag=${6:-"(💭 Thinking )"}

  local api_base_yaml=""
  if [[ -n "$url" ]]; then
    api_base_yaml="      api_base: \"$url\""
  fi

  # 36 chars perfectly fits the longest model name without the URL stretching it
  local line_out
  printf -v line_out "   ├─ %s : %-36s %s\n" "$label" "$model" "$think_tag"
  SUMMARY_OUTPUT+="$line_out"

  for idx in "${INDICES[@]}"; do
    cat << ENTRY
  - model_name: ${model_name}
    litellm_params:
      model: ${model}
      api_key: "os.environ/GEMINI_KEY_${idx}"
ENTRY
    if [[ -n "$api_base_yaml" ]]; then
      echo "$api_base_yaml"
    fi
    cat << ENTRY
    model_info:
${extra_yaml}
ENTRY
  done
}

