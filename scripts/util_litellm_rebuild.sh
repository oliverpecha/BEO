sed -i 's/\t/  /g' "$CONFIG_OUT"
SUMMARY_OUTPUT="${SUMMARY_OUTPUT%├─*}└─${SUMMARY_OUTPUT##*├─}"

echo ""
echo "✨ ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━ ✨"
echo "🚀  LiteLLM Configuration Rebuild Complete!   🚀"
echo "✨ ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━ ✨"
echo ""
echo " 📁 Destination : $CONFIG_OUT"
echo ""
echo " 🔑 Dynamic Keys Loaded : ${#INDICES[@]} total (${INDICES[*]/#/GEMINI_KEY_})"
echo ""
echo " 🤖 Tier Mappings:"
echo "$SUMMARY_OUTPUT"
echo ""
