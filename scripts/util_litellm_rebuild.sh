# BEO — LiteLLM Configuration
# AUTO-GENERATED by ~/beo/scripts/util_litellm_rebuild.sh
# Do not hand-edit — re-run script to regenerate
# Generated: $(date)
# Keys loaded: ${#INDICES[@]} (${INDICES[*]/#/GEMINI_KEY_})
# ════════════════════════════════════════════════

general_settings:
  master_key: "\${LITELLM_MASTER_KEY}"
  allow_requests_on_db_unavailable: true

litellm_settings:
  cache: true
  cache_params:
    type: "redis"
    url: "redis://beo-redis:6379" # <--- THIS LINE WAS UPDATED
  no_cache_for_model:
    - "tier-4-extraction"
